#1. Input DNA Sequence
from Bio.Seq import Seq

dna = Seq("ATGGCTTTTTAA")

print("DNA Sequence:", dna)

#2. Transcription Process
mrna = dna.transcribe()

print("mRNA Sequence:", mrna)

#3. Translation Process
protein = mrna.translate()

print("Protein Sequence:", protein)

"""Keterangan:
- M = Methionine
- A = Alanine
- F = Phenylalanine
- *= Stop codon
"""

#4. Identify Start and Stop Codon
start_codon = "AUG"
stop_codons = ["UAA", "UAG", "UGA"]

print("Start Codon:", start_codon)

for codon in stop_codons:
    if codon in mrna:
        print("Stop Codon Found:", codon)

